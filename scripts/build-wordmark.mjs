// Hero wordmark: हज़रतगंज set in Tiro Devanagari Hindi, shaped (nukta and
// anusvara placed by the font's own rules) and converted to one SVG path, so
// the landing page needs no Devanagari font download.
//
//   src/components/landing/wordmark-path.ts
//
// Run: npm run build:wordmark
import * as fontkit from "fontkit";
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const TEXT = "हज़रतगंज"; // src/data/restaurant.ts → wordmark.devanagari

const font = fontkit.openSync(join(root, "node_modules/@fontsource/tiro-devanagari-hindi/files/tiro-devanagari-hindi-devanagari-400-normal.woff2"));
const run = font.layout(TEXT);

const round = (s) => s.replace(/-?\d+\.\d+/g, (n) => String(Math.round(+n)));
let x = 0;
let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
const parts = [];
run.glyphs.forEach((glyph, i) => {
  const p = run.positions[i];
  const gx = x + p.xOffset;
  const gy = p.yOffset;
  // Font units are y-up; SVG is y-down.
  parts.push(round(glyph.path.transform(1, 0, 0, -1, gx, -gy).toSVG()));
  const bb = glyph.bbox;
  if (bb.maxX > bb.minX) {
    minX = Math.min(minX, gx + bb.minX);
    maxX = Math.max(maxX, gx + bb.maxX);
    minY = Math.min(minY, gy + bb.minY);
    maxY = Math.max(maxY, gy + bb.maxY);
  }
  x += p.xAdvance;
});

const width = Math.ceil(maxX - minX);
const height = Math.ceil(maxY - minY);
const out = `// Generated by scripts/build-wordmark.mjs from Tiro Devanagari Hindi (SIL OFL). Do not edit.
export const WORDMARK = {
  text: ${JSON.stringify(TEXT)},
  viewBox: "${Math.floor(minX)} ${Math.floor(-maxY)} ${width} ${height}",
  /** Ink height as a share of the font size (1000 units per em). */
  heightEm: ${(height / font.unitsPerEm).toFixed(3)},
  d: ${JSON.stringify(parts.join(""))},
} as const;
`;
writeFileSync(join(root, "src/components/landing/wordmark-path.ts"), out);
console.log(`wordmark: ${run.glyphs.length} glyphs → ${width} × ${height} units, ${out.length} bytes`);
